def rows(items):
    """The label / rule / text row pattern used by FAQs and Recommendations."""
    out = ['      <div class="rows">']
    for label, paras in items:
        out.append('        <div class="row">')
        out.append('          <div class="row__rule"></div>')
        out.append('          <div class="row__body">')
        out.append(f'            <h3 class="row__label">{label}</h3>')
        for p in paras:
            out.append(f'            <p class="row__text">{p}</p>')
        out.append("          </div>")
        out.append("        </div>")
    out.append("      </div>")
    return "\n".join(out)


def section(title, body, note=None, extra_class=""):
    cls = f"section {extra_class}".strip()
    note_html = f'\n      <p class="section__note">{note}</p>' if note else ""
    return f"""  <main class="{cls}">
    <div class="wrap">
      <h2 class="section__title">{title}</h2>{note_html}
{body}
    </div>
  </main>"""


