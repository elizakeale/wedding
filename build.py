SAVE_THE_DATE_PAGES = ["home.html"]
FULL_PAGES = ["home.html", "itinerary.html", "recommendations.html", "faqs.html"]
ALL_PAGES = sorted(set(SAVE_THE_DATE_PAGES + FULL_PAGES) | {"homepage.html"})


def build(preview=False):
    global FULL, OUT_DIR

    if preview:
        FULL, OUT_DIR = True, PREVIEW_DIR
        shutil.rmtree(PREVIEW_DIR, ignore_errors=True)
        os.makedirs(PREVIEW_DIR, exist_ok=True)
        print("PREVIEW BUILD — full site, written to _preview/ only.")
        print("Nothing here is committed or published.\n")
    else:
        FULL, OUT_DIR = C.PHASE == "full", HERE
        print(f"PHASE = {C.PHASE!r}")

    if FULL:
        page("home.html", "E &amp; L Wedding",
             section("RSVP", rsvp_form(),
                     note=f"We kindly ask you to RSVP by {C.WEDDING['rsvp_deadline']}.",
                     extra_class="rsvp"),
             tall=True,
             scripts='\n  <script src="js/rsvp.js"></script>')
        page("itinerary.html", "Itinerary &mdash; E &amp; L Wedding", itinerary_section())
        page("recommendations.html", "Recommendations &mdash; E &amp; L Wedding",
             section("Recommendations", rows(C.RECOMMENDATIONS)))
        page("faqs.html", "FAQs &mdash; E &amp; L Wedding", faq_section())
        live = FULL_PAGES
    else:
        page("home.html", "E &amp; L Wedding &mdash; Save the Date",
             faq_section(), tall=True, save_the_date=True)
        live = SAVE_THE_DATE_PAGES

    # Keep old shared links working: homepage.html was the entry page before
    # the pages were consolidated. Remove once no one is using that URL.
    write("homepage.html", f"""<!DOCTYPE html>
<html lang="en">
{GENERATED_BANNER}<head>
  <meta charset="UTF-8" />
  <meta name="robots" content="noindex, nofollow" />
  <meta http-equiv="refresh" content="0; url={C.ENTRY_PAGE}" />
  <link rel="canonical" href="{C.ENTRY_PAGE}" />
  <title>E &amp; L Wedding</title>
</head>
<body>
  <p>Redirecting to <a href="{C.ENTRY_PAGE}">the wedding site</a>&hellip;</p>
  <script>location.replace('{C.ENTRY_PAGE}');</script>
</body>
</html>
""")
    live = list(live) + ["homepage.html"]

    if preview:
        for name in PREVIEW_ASSETS:
            src = os.path.join(HERE, name)
            if not os.path.exists(src):
                continue
            dst = os.path.join(PREVIEW_DIR, name)
            if os.path.isdir(src):
                shutil.copytree(src, dst, dirs_exist_ok=True)
            else:
                shutil.copy2(src, dst)
        # The gate is skipped on purpose: the preview drops you straight onto
        # the site rather than making you retype the password each reload.
        print("\n  copied assets (css, js, images)")
        print("\n  Open it with either of these:")
        print("    VS Code   — right-click _preview/home.html, 'Open with Live Server'")
        print(f"    Terminal  — cd '{HERE}/_preview' && python3 -m http.server 8080")
        print("                then go to http://localhost:8080/home.html")
        print("\n  _preview/ is gitignored. Delete it any time; rebuild with --preview.")
        print("\nDone.")
        return

    stale = [p for p in ALL_PAGES if p not in live and os.path.exists(os.path.join(HERE, p))]
    if stale:
        print("\n  Stale pages from another phase (delete these so they don't ship):")
        for p in stale:
            print(f"    git rm {p}")

    update_gate()
    print("\nDone.")


GATE_START = "<!-- social-meta:start (generated by build.py — do not edit by hand) -->"
GATE_END = "<!-- social-meta:end -->"


def update_gate():
    """Keep index.html's shareable bits in sync with content.py.

    index.html is hand-written (it carries the password logic), so it is not
    regenerated. But the link-preview tags, the redirect target and the asset
    versions must match the rest of the site or the gate quietly drifts — and
    the gate is the page people actually share, so its tags are the ones that
    matter most.
    """
    path = os.path.join(HERE, "index.html")
    if not os.path.exists(path):
        print("\n  ! index.html (password gate) is missing.")
        return

    with open(path, encoding="utf-8") as f:
        gate = original = f.read()

    block = f"{GATE_START}\n{social_meta()}\n  {GATE_END}"
    if GATE_START in gate and GATE_END in gate:
        gate = re.sub(re.escape(GATE_START) + r".*?" + re.escape(GATE_END),
                      block, gate, flags=re.S)
    else:
        gate = gate.replace("</head>", f"{block}\n</head>", 1)

    # Redirect target
    gate, n = re.subn(r"(location(?:\.href|\.replace)?\s*[=(]\s*')[^']+\.html(')",
                      rf"\g<1>{C.ENTRY_PAGE}\g<2>", gate)
    if n == 0:
        print("\n  ! Could not find the redirect target in index.html — check it by hand.")

    # Asset versions
    gate = re.sub(r"(favicon\.(?:ico|png)\?v=)\d+", rf"\g<1>{C.ASSET_VERSION}", gate)

    if gate != original:
        with open(path, "w", encoding="utf-8") as f:
            f.write(gate)
        print("  updated index.html (link-preview tags, redirect, asset versions)")
    else:
        print("  index.html already up to date")


if __name__ == "__main__":
    args = set(sys.argv[1:])
    if args - {"--preview"}:
        print(__doc__)
        print("Usage:\n  python3 build.py            build the live site\n"
              "  python3 build.py --preview  build the full site into _preview/")
        sys.exit(1)
    build(preview="--preview" in args)
